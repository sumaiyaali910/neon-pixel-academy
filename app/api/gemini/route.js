/**
 * Next.js App Router Server Route (`/api/gemini`)
 *
 * Securely handles general-purpose & educational Gemini API requests on the server side.
 * Fetches the API key exclusively from `process.env.GEMINI_API_KEY`.
 * Never exposes keys to the frontend client.
 */
import { NextResponse } from 'next/server';

export async function POST(request) {
  try {
    const apiKey = process.env.GEMINI_API_KEY;
    const body = await request.json();
    const { prompt, subject = 'General', mode = 'general', history = [] } = body;

    if (!prompt || typeof prompt !== 'string') {
      return NextResponse.json(
        { error: 'A valid `prompt` string is required.' },
        { status: 400 }
      );
    }

    if (!apiKey) {
      return NextResponse.json(
        {
          error: 'GEMINI_API_KEY is not configured in the server environment.',
          fallbackMode: true,
          reply:
            '⚡ [PIXEL-OWL 9000]: `process.env.GEMINI_API_KEY` is not set in `.env.local` yet. Set `GEMINI_API_KEY` in your server environment to unlock live Gemini 2.5 Flash responses!',
        },
        { status: 200 }
      );
    }

    const systemInstruction = `You are PIXEL-OWL 9000, a brilliant, versatile, and friendly general-purpose AI assistant (powered by Google Gemini) inside the Neon Pixel Academy lounge.
You can answer ANY question on ANY topic — general knowledge, daily life, coding, creative writing, advice, math, science, gaming, history, pop culture, or casual conversation — just like Google Gemini!
When the user asks an academic or technical question, provide clear explanations and step-by-step solutions. When they ask a general or casual question, answer naturally, directly, and helpfully.`;

    // Format conversation history if provided
    const contents = [
      ...history.map((msg) => ({
        role: msg.role === 'assistant' ? 'model' : 'user',
        parts: [{ text: String(msg.content || '') }],
      })),
      {
        role: 'user',
        parts: [{ text: prompt }],
      },
    ];

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          system_instruction: {
            parts: [{ text: systemInstruction }],
          },
          contents,
          generationConfig: {
            temperature: 0.7,
            maxOutputTokens: 1500,
          },
        }),
      }
    );

    if (!response.ok) {
      const errData = await response.json().catch(() => ({}));
      return NextResponse.json(
        {
          error: errData?.error?.message || `Gemini API returned status ${response.status}`,
        },
        { status: response.status }
      );
    }

    const data = await response.json();
    const reply =
      data?.candidates?.[0]?.content?.parts?.[0]?.text ||
      'No response generated by Gemini.';

    return NextResponse.json({
      reply,
      model: 'gemini-2.5-flash',
      subject,
      mode,
    });
  } catch (error) {
    console.error('Error in /api/gemini route:', error);
    return NextResponse.json(
      { error: 'Internal Server Error while communicating with Gemini API.' },
      { status: 500 }
    );
  }
}
